// vendor-hash-wasm.cjs — hash-wasm argon2 瀏覽器載體 vendor 產生器（0.3.1 批 A3；@scure/bip39 母型：devDeps＋生成期 vendor）。
// 執行：node scripts/vendor-hash-wasm.cjs（需 npm ci 裝齊 devDeps）。
// 產物：src/client/vendor/hash-wasm-argon2.ts——hash-wasm dist/argon2.umd.min.js 原檔嵌於
// VENDOR-BEGIN／VENDOR-END 標記間（wasm 本體已是原檔內嵌 base64＝零網路請求），包進工廠函式
// hashWasmArgon2Factory()（區域 exports/module 讓 UMD 走 CommonJS 腿，零全域寫入）。
// 嵌入形＝原檔每個非空行前綴固定兩格縮排（[14] sideEffects 掃描是行首詞法——函式體內行首頂格
// 會被誤判頂層語句）；可逆：去每行兩格前綴＝原檔逐位元組（sha256 對帳即對還原後原文）。
// 縮排安全前提由下方形檢承載：原檔＝註解頭＋空行＋**單一**程式碼行（無跨行字面量可被縮排污染）。
// 產品碼零 runtime deps 鐵律：hash-wasm 只在 devDependencies；發行包帶的是 vendor 產物，不帶本產生器
//（package.json files 以 ! 排除——[22] scripts 封閉集 2 檔不動）。閘 [27] 不依賴本產生器：
// 只對 vendor 檔自身（標記間原文 sha256＝檔內常數＝閘釘選值）——升級 hash-wasm＝重生＋改閘釘選值。
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.join(__dirname, '..');
const PKG_DIR = path.join(ROOT, 'node_modules', 'hash-wasm');
const SRC = path.join(PKG_DIR, 'dist', 'argon2.umd.min.js');
const OUT = path.join(ROOT, 'src', 'client', 'vendor', 'hash-wasm-argon2.ts');

if (!fs.existsSync(SRC)) {
  console.error('ABORT: node_modules/hash-wasm 缺席——先跑 npm ci');
  process.exit(1);
}
const version = JSON.parse(fs.readFileSync(path.join(PKG_DIR, 'package.json'), 'utf8')).version;
const raw = fs.readFileSync(SRC, 'utf8');
if (!raw.endsWith('\n') || raw.includes('\r') || raw.includes('VENDOR-BEGIN') || raw.includes('VENDOR-END')) {
  console.error('ABORT: 原檔形不符（須 LF 結尾、無 CR、無標記字面）');
  process.exit(1);
}
const lines = raw.slice(0, -1).split('\n');
const codeLines = lines.filter((l) => l !== '' && !/^(\/\*!| \*)/.test(l));
if (codeLines.length !== 1 || lines[lines.length - 1] !== codeLines[0]) {
  console.error('ABORT: 原檔形變（預期註解頭＋單一程式碼行；縮排嵌入的安全前提失效——改嵌入形前禁重生）');
  process.exit(1);
}
const embedded = lines.map((l) => (l === '' ? '' : '  ' + l)).join('\n') + '\n';
const sha = crypto.createHash('sha256').update(raw, 'utf8').digest('hex');

const out = `// @ts-nocheck
/**
 * GENERATED by scripts/vendor-hash-wasm.cjs — 禁手改（重生：node scripts/vendor-hash-wasm.cjs）。
 *
 * hash-wasm@${version} dist/argon2.umd.min.js（MIT License, (c) Dani Biro — https://github.com/Daninet/hash-wasm）。
 * 原檔嵌於 VENDOR-BEGIN／VENDOR-END 標記間（每個非空行前綴兩格縮排；去縮排＝原檔逐位元組）；
 * sha256(還原原檔)＝HASH_WASM_ARGON2_SHA256（閘 [27] 對帳）。
 * 工廠函式自足（零外部參照）：argon-worker.ts 以 Function#toString 取其原文組 Worker blob——禁引入閉包外依賴。
 */
import type { HashWasmArgon2id } from '../argon2.ts';

export const HASH_WASM_VERSION = '${version}';
export const HASH_WASM_ARGON2_SHA256 = '${sha}';

export function hashWasmArgon2Factory(): { argon2id: HashWasmArgon2id } {
  var exports = {}, module = { exports: exports }, define = undefined;
  // VENDOR-BEGIN
${embedded}  // VENDOR-END
  return exports;
}
`;
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out, 'utf8');
console.log('VENDOR-HASH-WASM-OK ' + version + ' sha256=' + sha + ' → ' + path.relative(ROOT, OUT) + ' (' + Buffer.byteLength(out) + 'B)');
